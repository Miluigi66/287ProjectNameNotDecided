"""Convert a pixel-art sprite sheet into Quartus-compatible 24-bit RGB MIFs.

The supplied JSON layout controls frame cropping, so this script can also be
used for other sprite sheets by creating a corresponding JSON configuration.


Example:
    python sprite_sheet_to_mif.py linkSpriteSheet.png --config link_layout.json
"""

import argparse
import csv
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def parse_rgb_hex(value):
    color = value.strip().lstrip('#')
    if len(color) != 6:
        raise ValueError("transparent_rgb must have exactly 6 hexadecimal digits")
    try:
        return tuple(bytes.fromhex(color))
    except ValueError as exc:
        raise ValueError(f"Invalid RGB value: {value!r}") from exc


def read_logical_sheet(image_path, config):
    with Image.open(image_path) as source:
        source = source.convert("RGBA")
        if list(source.size) != config["source_size"]:
            raise ValueError(
                f"Image size {source.size} does not match layout source_size "
                f"{config['source_size']}. Use a matching layout JSON."
            )
        scale = int(config["scale"])
        if scale < 1 or source.width % scale or source.height % scale:
            raise ValueError("scale must evenly divide image width and height")
        reduced = source.resize((source.width // scale, source.height // scale),
                                Image.Resampling.NEAREST)

    # A 24-bit RGB memory word has no alpha channel. Map both transparent
    # pixels and the configured background color to a color key (black here).
    transparent_color = parse_rgb_hex(config["transparent_rgb"])
    pixels = reduced.load()
    for y in range(reduced.height):
        for x in range(reduced.width):
            r, g, b, alpha = pixels[x, y]
            if alpha < 128 or (r, g, b) == transparent_color:
                pixels[x, y] = (*transparent_color, 0)
            else:
                pixels[x, y] = (r, g, b, 255)
    return reduced


def crop_checked(image, x, y, width, height, description):
    if x < 0 or y < 0 or x + width > image.width or y + height > image.height:
        raise ValueError(f"{description} crop {(x, y, width, height)} outside {image.size}")
    return image.crop((x, y, x + width, y + height))


def isolated_frame(image, info, config, width, height):
    """Crop a frame without accidentally importing adjacent sprite pixels.

    Physical cells in the source sheet have irregular gaps. A 32x32 frame
    window can overlap a neighbor; the slot boundaries mask the neighbor out.
    """
    x, y = int(info["x"]), int(info["y"])
    col, row = int(info["column"]), int(info["row"])
    columns = config["column_boundaries"]
    rows = config["row_boundaries"]
    slot = (columns[col], rows[row], columns[col + 1], rows[row + 1])
    frame = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    ix0, iy0 = max(x, slot[0]), max(y, slot[1])
    ix1, iy1 = min(x + width, slot[2]), min(y + height, slot[3])
    if ix1 <= ix0 or iy1 <= iy0:
        raise ValueError(f"Frame {info['name']} does not overlap its sheet slot")
    source_part = image.crop((ix0, iy0, ix1, iy1))
    frame.paste(source_part, (ix0 - x, iy0 - y))

    # Detect actual artwork that does not fit the specified 32x32 window.
    source_cell = image.crop(slot)
    expected_pixels = sum(pixel[3] > 0 for pixel in pixels_of(source_cell))
    copied_pixels = sum(pixel[3] > 0 for pixel in pixels_of(source_part))
    if copied_pixels != expected_pixels:
        raise ValueError(
            f"Frame {info['name']} loses {expected_pixels - copied_pixels} pixels; "
            "adjust x/y in the layout JSON"
        )
    return frame


def pixels_of(image):
    """Compatible with both recent and older Pillow releases."""
    if hasattr(image, "get_flattened_data"):
        return image.get_flattened_data()
    return image.getdata()


def mif_write(path, tiles, tile_size, transparent_rgb):
    """Store each 16x16 tile in row-major order as 24-bit 0xRRGGBB values."""
    words_per_tile = tile_size * tile_size
    depth = len(tiles) * words_per_tile
    with path.open("w", encoding="ascii", newline="\n") as f:
        f.write("-- Generated by sprite_sheet_to_mif.py\n")
        f.write("-- RGB888; transparent pixels use the configured color key\n")
        f.write(f"-- Color key: {transparent_rgb.upper()}\n")
        f.write(f"WIDTH=24;\nDEPTH={depth};\n")
        f.write("ADDRESS_RADIX=HEX;\nDATA_RADIX=HEX;\nCONTENT BEGIN\n")
        address = 0
        for tile in tiles:
            if tile.size != (tile_size, tile_size):
                raise ValueError("Tile dimensions differ from tile_size")
            for r, g, b, a in pixels_of(tile):
                rgb_word = f"{r:02X}{g:02X}{b:02X}" if a >= 128 else transparent_rgb.upper()
                f.write(f"  {address:04X} : {rgb_word};\n")
                address += 1
        f.write("END;\n")
    return depth


def checker_background(size, scale=4):
    bg = Image.new("RGB", (size[0] * scale, size[1] * scale), "#D3D3D3")
    draw = ImageDraw.Draw(bg)
    block = 4 * scale
    for y in range(0, bg.height, block):
        for x in range(0, bg.width, block):
            if ((x // block) + (y // block)) % 2:
                draw.rectangle((x, y, x + block - 1, y + block - 1), fill="#969696")
    return bg


def preview_image(frames, metadata, path, cell_size, columns=4, pixel_scale=4):
    """Draw a labeled contact sheet with a visible 16-pixel tile grid."""
    tile_display = cell_size * pixel_scale
    margin, caption_h, gap = 12, 37, 12
    rows = (len(frames) + columns - 1) // columns
    w = margin * 2 + columns * tile_display + (columns - 1) * gap
    h = margin * 2 + rows * (tile_display + caption_h) + (rows - 1) * gap
    page = Image.new("RGB", (w, h), "#EFEFEF")
    draw = ImageDraw.Draw(page)
    font = ImageFont.load_default()
    for index, (frame, info) in enumerate(zip(frames, metadata)):
        col, row = index % columns, index // columns
        left = margin + col * (tile_display + gap)
        top = margin + row * (tile_display + caption_h + gap)
        backdrop = checker_background((cell_size, cell_size), pixel_scale)
        enlarged = frame.resize((tile_display, tile_display), Image.Resampling.NEAREST)
        backdrop.paste(enlarged, mask=enlarged.getchannel("A"))
        page.paste(backdrop, (left, top))
        if cell_size == 32:
            draw.line((left + tile_display // 2, top, left + tile_display // 2,
                       top + tile_display), fill="#454545", width=1)
            draw.line((left, top + tile_display // 2, left + tile_display,
                       top + tile_display // 2), fill="#454545", width=1)
        draw.text((left, top + tile_display + 3), f"ID {info['frame_id']:02d}",
                  fill="black", font=font)
        draw.text((left, top + tile_display + 17), info["name"], fill="black", font=font)
    page.save(path)


def convert(image_path, config_path, out_dir):
    config = json.loads(config_path.read_text(encoding="utf-8"))
    image = read_logical_sheet(image_path, config)
    tile_size = int(config["tile_size"])
    width, height = int(config["frame_width"]), int(config["frame_height"])
    if (width, height) != (2 * tile_size, 2 * tile_size):
        raise ValueError("This version expects each frame to be a 2x2 grid of tiles")
    if tile_size != 16:
        raise ValueError("This version targets 16x16 FPGA tiles")

    out_dir.mkdir(parents=True, exist_ok=True)
    full_frames, full_tiles, base_frames = [], [], []
    index, base_index = [], []
    for frame_id, info in enumerate(config["frames"]):
        name = str(info["name"])
        frame = isolated_frame(image, info, config, width, height)
        if not any(alpha > 0 for *rgb, alpha in pixels_of(frame)):
            raise ValueError(f"Frame {name} is empty; check layout coordinates")
        full_frames.append(frame)
        # Tile order: top-left (0), top-right (1), bottom-left (2), bottom-right (3)
        for tile_y in range(2):
            for tile_x in range(2):
                full_tiles.append(frame.crop((tile_x * tile_size, tile_y * tile_size,
                                              (tile_x + 1) * tile_size,
                                              (tile_y + 1) * tile_size)))
        record = {
            "frame_id": frame_id, "name": name,
            "sheet_row": info["row"], "sheet_column": info["column"],
            "tile_ids": [4 * frame_id + i for i in range(4)],
            "source_origin": [info["x"], info["y"]],
            "base_sprite_id": None,
        }
        if "base_crop" in info:
            bx, by = map(int, info["base_crop"])
            body = crop_checked(image, bx, by, 16, 16, f"Base sprite {name}")
            base_id = len(base_frames)
            base_frames.append(body)
            record["base_sprite_id"] = base_id
            base_index.append({"sprite_id": base_id, "name": name,
                               "sheet_row": info["row"],
                               "sheet_column": info["column"],
                               "source_origin": [bx, by]})
        index.append(record)

    full_depth = mif_write(out_dir / "link_sprites_16x16_tiles.mif",
                           full_tiles, tile_size, config["transparent_rgb"])
    base_depth = mif_write(out_dir / "link_basic_16x16.mif",
                           base_frames, tile_size, config["transparent_rgb"])
    preview_image(full_frames, index, out_dir / "preview_all_frames.png", 32)
    base_metadata = [{"frame_id": b["sprite_id"], "name": b["name"]} for b in base_index]
    preview_image(base_frames, base_metadata, out_dir / "preview_basic.png", 16, pixel_scale=8)

    metadata = {
        "source_image": image_path.name,
        "logical_sheet_size": list(image.size),
        "pixel_format": "RGB888 (24 bits)",
        "transparent_color": config["transparent_rgb"].upper(),
        "sprite_tile_size": [16, 16],
        "full_frame_size": [32, 32],
        "full_mif": "link_sprites_16x16_tiles.mif",
        "full_mif_depth": full_depth,
        "tile_count": len(full_tiles),
        "base_mif": "link_basic_16x16.mif",
        "base_mif_depth": base_depth,
        "base_sprite_count": len(base_frames),
        "full_frames": index,
        "base_sprites": base_index,
        "full_address_formula": "(frame_id*4 + ((local_y>>4)*2) + (local_x>>4))*256 + ((local_y&15)*16) + (local_x&15)",
        "base_address_formula": "sprite_id*256 + local_y*16 + local_x",
    }
    (out_dir / "sprite_index.json").write_text(json.dumps(metadata, indent=2) + "\n",
                                               encoding="utf-8")
    with (out_dir / "sprite_index.csv").open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(["frame_id", "name", "sheet_row", "sheet_column",
                         "tile_top_left", "tile_top_right", "tile_bottom_left",
                         "tile_bottom_right", "base_sprite_id"])
        for row in index:
            writer.writerow([row["frame_id"], row["name"], row["sheet_row"],
                             row["sheet_column"], *row["tile_ids"],
                             "" if row["base_sprite_id"] is None else row["base_sprite_id"]])
    print(f"Downscaled source: {image.width} x {image.height} pixels")
    print(f"Created {len(index)} frames => {len(full_tiles)} 16x16 tiles => {full_depth:,} words")
    print(f"Created {len(base_frames)} basic sprites => {base_depth:,} words")
    print(f"All outputs in: {out_dir.resolve()}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", nargs="?", default="linkSpriteSheet.png",
                        type=Path, help="Image file (default: linkSpriteSheet.png)")
    parser.add_argument("--config", type=Path, default=Path("link_layout.json"),
                        help="JSON defining crop positions (default: link_layout.json)")
    parser.add_argument("--out-dir", type=Path, default=Path("output"),
                        help="Directory for generated files (default: output)")
    args = parser.parse_args()
    convert(args.image, args.config, args.out_dir)


if __name__ == "__main__":
    main()
